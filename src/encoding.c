#include <string.h>

#include "nulib.h"
#include "nulib/utfsjis.h"
#include "ai5/mes.h"

#include "encoding.h"

enum text_encoding text_encoding = TEXT_ENCODING_SJIS;

// generated by tools/gen_cp949_table.py
extern const uint16_t cp949_table[0xfe - 0x81 + 1][0xfe - 0x41 + 1];

static unsigned cp949_lookup(uint8_t lead, uint8_t trail)
{
	if (lead < 0x81 || lead > 0xfe || trail < 0x41 || trail > 0xfe)
		return 0;
	return cp949_table[lead - 0x81][trail - 0x41];
}

bool ai5_char_is_zenkaku(uint8_t b)
{
	if (text_encoding_is_cp949())
		return b >= 0x81 && b <= 0xfe;
	return mes_char_is_zenkaku(b);
}

bool ai5_char_is_hankaku(uint8_t b)
{
	if (text_encoding_is_cp949())
		return b < 0x80;
	return mes_char_is_hankaku(b);
}

bool ai5_char_is_2byte(uint8_t b)
{
	if (text_encoding_is_cp949())
		return b >= 0x81 && b <= 0xfe;
	return SJIS_2BYTE(b);
}

const char *ai5_char_to_unicode(const char *src, int *dst)
{
	if (!text_encoding_is_cp949())
		return sjis_char2unicode(src, dst);

	const uint8_t *s = (const uint8_t*)src;
	if (s[0] < 0x81 || s[0] == 0xff || !s[1]) {
		*dst = s[0];
		return src + 1;
	}
	unsigned u = cp949_lookup(s[0], s[1]);
	if (!u) {
		// Not valid CP949. Translations sometimes leave Shift-JIS
		// characters (e.g. the full-width space 0x8140) in place.
		sjis_char2unicode(src, dst);
		if (*dst == 0)
			*dst = ' ';
		return src + 2;
	}
	*dst = u;
	return src + 2;
}

static string utf8_push(string s, unsigned u)
{
	char b[4];
	size_t n;
	if (u < 0x80) {
		b[0] = u;
		n = 1;
	} else if (u < 0x800) {
		b[0] = 0xc0 | (u >> 6);
		b[1] = 0x80 | (u & 0x3f);
		n = 2;
	} else {
		b[0] = 0xe0 | (u >> 12);
		b[1] = 0x80 | ((u >> 6) & 0x3f);
		b[2] = 0x80 | (u & 0x3f);
		n = 3;
	}
	return string_concat_len(s, b, n);
}

string ai5_cstring_to_utf8(const char *src, size_t len)
{
	if (!text_encoding_is_cp949())
		return sjis_cstring_to_utf8(src, len);

	if (!len)
		len = strlen(src);
	const char *end = src + len;
	string out = string_empty();
	while (src < end && *src) {
		int ch;
		src = ai5_char_to_unicode(src, &ch);
		out = utf8_push(out, ch);
	}
	return out;
}
